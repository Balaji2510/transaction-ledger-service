import { describe, it, expect, beforeEach } from 'vitest';
import request from 'supertest';
import { createApp } from '../../src/app/app.js';
import { InMemoryAccountRepository } from '../../src/modules/accounts/repositories/in-memory-account.repository.js';

describe('POST /api/v1/accounts (Create Account API Integration)', () => {
  let repository: InMemoryAccountRepository;
  let app: ReturnType<typeof createApp>;

  beforeEach(() => {
    repository = new InMemoryAccountRepository();
    app = createApp({ accountRepository: repository });
  });

  describe('Success Cases', () => {
    it('should create an account successfully with required name, balance 0, and system generated created_at', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          name: 'John Doe',
        });

      expect(response.status).toBe(201);
      expect(response.body.success).toBe(true);
      expect(response.body.data).toMatchObject({
        name: 'John Doe',
        balance: 0,
      });
      expect(response.body.data.id).toBeDefined();
      expect(typeof response.body.data.id).toBe('string');
      expect(response.body.data.created_at).toBeDefined();
      expect(new Date(response.body.data.created_at).toISOString()).toBe(response.body.data.created_at);
    });

    it('should allow providing a unique id', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          id: 'acc_unique_999',
          name: 'Jane Doe',
        });

      expect(response.status).toBe(201);
      expect(response.body.data.id).toBe('acc_unique_999');
      expect(response.body.data.name).toBe('Jane Doe');
      expect(response.body.data.balance).toBe(0);
    });
  });

  describe('Validation & Business Rule Enforcement', () => {
    it('should reject request when name is missing', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({});

      expect(response.status).toBe(400);
      expect(response.body.success).toBe(false);
      expect(response.body.error).toBeDefined();
      expect(response.body.error.code).toBe('BAD_REQUEST');
      expect(response.body.error.message).toMatch(/name is required/i);
    });

    it('should reject request when name is empty string or only whitespace', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({ name: '    ' });

      expect(response.status).toBe(400);
      expect(response.body.success).toBe(false);
      expect(response.body.error.message).toMatch(/name is required and cannot be empty/i);
    });

    it('should reject request when client attempts to set initial balance', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          name: 'Malicious Actor',
          balance: 1000,
        });

      expect(response.status).toBe(400);
      expect(response.body.success).toBe(false);
      expect(response.body.error.message).toMatch(/Client is not allowed to set the initial balance/i);
    });

    it('should reject request even when client attempts to pass balance: 0', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          name: 'Strict Actor',
          balance: 0,
        });

      expect(response.status).toBe(400);
      expect(response.body.success).toBe(false);
      expect(response.body.error.message).toMatch(/Client is not allowed to set the initial balance/i);
    });

    it('should reject request when client attempts to provide created_at', async () => {
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          name: 'Time Traveler',
          created_at: '2020-01-01T00:00:00.000Z',
        });

      expect(response.status).toBe(400);
      expect(response.body.success).toBe(false);
      expect(response.body.error.message).toMatch(/created_at is generated by the system/i);
    });

    it('should reject request with 409 Conflict when account id already exists', async () => {
      // Create first account
      await request(app)
        .post('/api/v1/accounts')
        .send({
          id: 'acc_conflict_test',
          name: 'First User',
        });

      // Attempt to create second account with same id
      const response = await request(app)
        .post('/api/v1/accounts')
        .send({
          id: 'acc_conflict_test',
          name: 'Duplicate User',
        });

      expect(response.status).toBe(409);
      expect(response.body.success).toBe(false);
      expect(response.body.error.code).toBe('CONFLICT');
      expect(response.body.error.message).toContain("Account with id 'acc_conflict_test' already exists");
    });
  });

  describe('Account Retrieval Verification', () => {
    it('should be able to retrieve created account via GET /api/v1/accounts/:id', async () => {
      const createRes = await request(app)
        .post('/api/v1/accounts')
        .send({ name: 'Verify Get' });

      const accountId = createRes.body.data.id;

      const getRes = await request(app).get(`/api/v1/accounts/${accountId}`);
      expect(getRes.status).toBe(200);
      expect(getRes.body.data.id).toBe(accountId);
      expect(getRes.body.data.balance).toBe(0);
      expect(getRes.body.data.name).toBe('Verify Get');
    });

    it('should return 404 for non-existent account ID', async () => {
      const res = await request(app).get('/api/v1/accounts/non-existent-id');
      expect(res.status).toBe(404);
      expect(res.body.success).toBe(false);
      expect(res.body.error.code).toBe('NOT_FOUND');
    });
  });
});

