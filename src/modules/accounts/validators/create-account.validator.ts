import { z } from 'zod';

export const createAccountBodySchema = z.object({
  id: z
    .string({ error: 'id must be a string' })
    .trim()
    .min(1, 'id cannot be an empty string')
    .optional(),
  name: z
    .string({ error: 'name is required' })
    .trim()
    .min(1, 'name is required and cannot be empty'),
  balance: z.unknown().optional(),
  created_at: z.unknown().optional(),
}).superRefine((val, ctx) => {
  if (val.balance !== undefined) {
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      message: 'Client is not allowed to set the initial balance. Initial balance must always be 0.',
      path: ['balance'],
    });
  }
  if (val.created_at !== undefined) {
    ctx.addIssue({
      code: z.ZodIssueCode.custom,
      message: 'created_at is generated by the system and cannot be supplied by the client.',
      path: ['created_at'],
    });
  }
});

export type CreateAccountInput = z.infer<typeof createAccountBodySchema>;
