import { v4 as uuidv4 } from 'uuid';
import { Account, AccountBalanceDTO, CreateAccountDTO } from '../models/account.entity.js';
import { IAccountRepository } from '../repositories/account.repository.interface.js';
import { BadRequestError, ConflictError, NotFoundError } from '../../../common/errors/index.js';

export class AccountService {
  constructor(private readonly accountRepository: IAccountRepository) {}

  /**
   * Creates a new ledger account.
   * Enforces business constraints:
   * - id must be unique
   * - name is required
   * - initial balance is always 0 (client cannot override)
   * - created_at is generated by system
   */
  async createAccount(dto: CreateAccountDTO): Promise<Account> {
    const trimmedName = dto.name.trim();

    let accountId = dto.id?.trim();
    if (accountId) {
      const exists = await this.accountRepository.existsById(accountId);
      if (exists) {
        throw new ConflictError(`Account with id '${accountId}' already exists`);
      }
    } else {
      accountId = uuidv4();
    }

    const newAccount: Account = {
      id: accountId,
      name: trimmedName,
      balance: 0,
      created_at: new Date().toISOString(),
    };

    return this.accountRepository.create(newAccount);
  }

  /**
   * Retrieves an account by its unique ID.
   */
  async getAccountById(id: string): Promise<Account> {
    const account = await this.accountRepository.findById(id);
    if (!account) {
      throw new NotFoundError(`Account with id '${id}' not found`);
    }
    return account;
  }

  /**
   * Retrieves current balance of an account by its unique ID.
   * Throws NotFoundError if account does not exist.
   */
  async getAccountBalance(id: string): Promise<AccountBalanceDTO> {
    const trimmedId = id?.trim();
    if (!trimmedId) {
      throw new BadRequestError('Account ID is required and cannot be empty');
    }

    const balanceData = await this.accountRepository.findBalanceById(trimmedId);
    if (!balanceData) {
      throw new NotFoundError(`Account with id '${trimmedId}' not found`);
    }

    return balanceData;
  }

  /**
   * Retrieves all accounts in the ledger.
   */
  async getAllAccounts(): Promise<Account[]> {
    return this.accountRepository.findAll();
  }
}

